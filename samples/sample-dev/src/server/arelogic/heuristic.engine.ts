export function updateHeuristics(E:number[]){
 const next = new Array(13).fill(0);
 for(let i=0;i<13;i++){
  for(let j=0;j<13;j++){
   next[i]+=M[i][j]*H[j];
  }
  next[i]+=E[i]||0;
 }
 for(let i=0;i<13;i++){
     H[i] = next[i];
 }
 saveState({ H: [...H] });
 return [...H];
}
