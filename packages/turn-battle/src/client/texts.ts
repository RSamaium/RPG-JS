/** Texts given by the game (`texts` option): they win over the catalog of the language. */
export const TEXTS: Record<string, string> = {};

let readLocale: () => string = () => "en";

/** The battle UI follows the language of the game: `read` is the locale of the engine, reactive inside a computation. */
export const followLocale = (read: () => string) => (readLocale = read);

/** English when the catalog does not hold the language (`fr-CA` falls back to `fr`). */
export const t = (key: string) => {
  const locale = readLocale().toLowerCase();
  return TEXTS[key] ?? (TEXTS_BY_LOCALE[locale] ?? TEXTS_BY_LOCALE[locale.split("-")[0]] ?? TEXTS_BY_LOCALE.en)[key] ?? TEXTS_BY_LOCALE.en[key] ?? key;
};
